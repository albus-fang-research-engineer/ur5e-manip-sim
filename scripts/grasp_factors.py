"""Which grasp factor decides whether the object stays in the hand? Same planner
and motion (OmniManip), one factor changed at a time, then physics.

    python3 scripts/grasp_factors.py programs --out DIR     # one program per variant
    # for each DIR/<name>.json: plan_omnimanip.py --program it --out DIR/<name>.npz,
    # then execute_task_plan.py --plan DIR/<name>.npz, and move its _exec.json to DIR
    python3 scripts/grasp_factors.py table --dir DIR --spec tasks/specs/insert_marker.json \\
        --out outputs/comparison/insert_marker_grasp_factors

Variants are named after what they change from the base grasp, 22 mm along the
shaft, 3.9 mm above its axis, closing axis level and square to the shaft.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from scripts.compare_plans import markdown_table, physics_outcome  # noqa: E402

BASE_PROGRAM = "manip_sim/omnimanip/programs/insert_marker.json"
Y0, Z0 = 22.0, 3.9            # mm
GROUPS = {
    "Along the shaft, height 3.9 mm": [("y", y, dict(y=y)) for y in (8, 12, 14, 16, 18, 20, 21, 22, 23, 24, 26, 28, 30, 35)],
    "Height above the shaft's axis": [("z", z, dict(z=z)) for z in (0, 2, 3.9, 6, 8, 10)],
    "Along the shaft, height 8 mm": [("yz8_y", y, dict(y=y, z=8)) for y in (8, 16, 22, 35)],
    "Closing axis tilted off the table": [("tilt", a, dict(tilt=a)) for a in (-15, -10, -5, -2, 0, 2, 5, 10, 15)],
    "Closing axis off square to the shaft": [("yaw", b, dict(yaw=b)) for b in (0, 3, 5, 10, 15)],
}


def program(base: dict, y=Y0, z=Z0, tilt=0.0, yaw=0.0) -> dict:
    p = json.loads(json.dumps(base))
    t, b = math.radians(tilt), math.radians(yaw)
    p["grasp"]["point_body"] = [0.0, y / 1000, z / 1000]
    p["grasp"]["approach_world"] = [math.sin(t), 0.0, -math.cos(t)]    # tilts the closing axis off the table
    p["grasp"]["closing_body"] = [math.cos(b), math.sin(b), 0.0]       # turns it off square to the shaft
    return p


def write_programs(out: Path) -> None:
    base = json.loads(Path(BASE_PROGRAM).read_text())
    out.mkdir(parents=True, exist_ok=True)
    for variants in GROUPS.values():
        for prefix, value, kw in variants:
            (out / f"grip_{prefix}{value}.json").write_text(json.dumps(program(base, **kw), indent=1))


def row(directory: Path, name: str, value, rim_radius: float) -> tuple:
    metrics_path, report_path = directory / f"{name}_exec.json", directory / f"{name}.report.json"
    if not metrics_path.exists():
        failure = json.loads(report_path.read_text()).get("failure", {}).get("message", "") if report_path.exists() else "not run"
        return (value, "no plan", "–", "–", failure)
    m = json.loads(metrics_path.read_text())
    slip = max((s.get("slip_max_mm") or 0.0 for s in m["segments"].values()), default=0.0)
    return (value, physics_outcome(m, rim_radius), m.get("grasp_contacts"), round(slip, 1), "")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("mode", choices=("programs", "table"))
    ap.add_argument("--dir", type=Path)
    ap.add_argument("--spec")
    ap.add_argument("--out", required=True, type=Path)
    args = ap.parse_args()
    if args.mode == "programs":
        write_programs(args.out)
        return
    rim = json.loads(Path(args.spec).read_text())["rim_radius_m"]
    sections, data = ["# Grasp factors: insert_marker, OmniManip motion", "Generated by scripts/grasp_factors.py."], {}
    for title, variants in GROUPS.items():
        rows = [row(args.dir, f"grip_{prefix}{value}", value, rim) for prefix, value, _ in variants]
        data[title] = rows
        sections += [f"## {title}", markdown_table([("Value", "Outcome", "Contacts", "Largest slip mm", "Plan failure")] + rows)]
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.with_suffix(".md").write_text("\n\n".join(sections) + "\n")
    args.out.with_suffix(".json").write_text(json.dumps(data, indent=2) + "\n")


if __name__ == "__main__":
    main()
